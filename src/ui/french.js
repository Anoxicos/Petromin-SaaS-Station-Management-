const translateTree = (root) => {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const parent = node.parentElement;
    if (!parent || parent.closest("script,style,textarea,[contenteditable=true]")) continue;
    const original = node.nodeValue.trim();
    const translated = fr.get(original);
    if (translated && translated !== original) node.nodeValue = node.nodeValue.replace(original, translated);
  }
  translateAttributes(root);
};

const translateAttributes = (root) => {
  const elements = [];
  if (root.nodeType === Node.ELEMENT_NODE) elements.push(root);
  elements.push(...(root.querySelectorAll?.("[placeholder],[aria-label],[title]") || []));
  for (const element of elements) {
    for (const attribute of ["placeholder", "aria-label", "title"]) {
      const original = element.getAttribute(attribute);
      const translated = original && fr.get(original);
      if (translated && translated !== original) element.setAttribute(attribute, translated);
    }
  }
};

const translateTextNode = (node) => {
  const parent = node.parentElement;
  if (!parent || parent.closest("script,style,textarea,[contenteditable=true]")) return;
  const original = node.nodeValue;
  const trimmed = original.trim();
  const translated = fr.get(trimmed);
  if (translated && translated !== trimmed) node.nodeValue = original.replace(trimmed, translated);
};

